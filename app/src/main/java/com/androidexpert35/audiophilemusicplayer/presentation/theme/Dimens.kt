package com.androidexpert35.audiophilemusicplayer.presentation.theme

import androidx.compose.ui.unit.dp

/**
 * Spacing tokens for the Audiophile Music Player design system.
 *
 * Provides a consistent set of padding/margin values used throughout
 * the app's composables. Named using a t-shirt size scale for clarity.
 */

/** 2.dp — hairline spacing for tight visual grouping. */
val paddingXSSmall = 2.dp

/** 4.dp — subtle inner padding (e.g., tag outlines, divider offsets). */
val paddingSSmall = 4.dp

/** 8.dp — compact spacing between tightly related elements. */
val paddingSmall = 8.dp

/** 12.dp — small gap for closely related content. */
val paddingSMedium = 12.dp

/** 16.dp — standard spacing for cards, sections, and form fields. */
val paddingMedium = 16.dp

/** 24.dp — generous spacing between distinct visual sections. */
val paddingLarge = 24.dp

/** 32.dp — extra-large gap for hero regions and modal internals. */
val paddingXLarge = 32.dp

/** 48.dp — double extra-large, used for large loading indicators. */
val paddingXXLarge = 48.dp

